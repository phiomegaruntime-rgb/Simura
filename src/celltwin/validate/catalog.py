"""A curated catalog of open / openly-licensed battery datasets.

This is a *directory*, not a data store. CellTwin does **not** redistribute any
real dataset -- the files are large and each carries its own license. What we
ship is metadata: where to find each dataset, under what license, how to cite it,
what it is good for validating, and which loader parses its format
(:mod:`celltwin.validate.loaders`). The user downloads a dataset themselves and
points a loader at it.

The one exception is ``demo-synthetic``: a tiny, clearly-labelled *synthetic*
sample generated by CellTwin's own simulator, bundled so the validation pipeline
(CLI, tests, dashboard demo) runs offline out of the box. It is **not** real
laboratory data and must not be treated as such.

Honesty note: the ``license``/``citation`` strings below are curated best-effort
metadata. Licenses and citation requirements can change -- **verify against the
dataset's own homepage before you redistribute or publish results.**
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any

from ..sim import chemistry_key_for


@dataclass(frozen=True)
class DatasetSpec:
    """Metadata describing one open battery dataset (or the synthetic demo)."""

    id: str
    name: str
    institution: str
    chemistry: str          # e.g. "NMC", "LFP", "LCO", "NCA" (informational)
    cell_format: str        # e.g. "18650", "21700", "pouch"
    license: str            # short label, e.g. "CC-BY-4.0", "US Gov public domain"
    license_url: str
    citation: str
    homepage_url: str
    download_url: str
    loader: str             # key into loaders.loader_for()
    what_it_validates: tuple[str, ...]
    sample: str | None = None   # bundled sample filename (only the synthetic demo)
    synthetic: bool = False
    notes: str = ""

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["what_it_validates"] = list(self.what_it_validates)
        return d


