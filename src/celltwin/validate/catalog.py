_BY_ID = {d.id: d for d in DATASETS}


def list_datasets() -> list[DatasetSpec]:
    """Every catalog entry (synthetic demo first, then real datasets)."""
    return list(DATASETS)


def get_dataset(dataset_id: str) -> DatasetSpec:
    """Look up one dataset by id, raising a helpful error if it's unknown."""
    try:
        return _BY_ID[dataset_id]
    except KeyError:
        known = ", ".join(sorted(_BY_ID))
        raise KeyError(f"unknown dataset '{dataset_id}'. known ids: {known}") from None


def datasets_for_chemistry(chemistry: str) -> list[DatasetSpec]:
    """Catalog entries whose chemistry label contains ``chemistry`` (case-insensitive)."""
    q = chemistry.strip().lower()
    return [d for d in DATASETS if q in d.chemistry.lower()]


def synthetic_for(chemistry: str) -> DatasetSpec:
    """Pick the bundled synthetic sample whose chemistry matches ``chemistry``.

    Used by the in-browser demo so selecting an LFP dataset validates against the
    LFP synthetic sample (and the LFP OCV curve), not the NMC one. Falls back to
    the NMC demo when no chemistry-matched sample is bundled.
    """
    key = chemistry_key_for(chemistry)
    for d in DATASETS:
        if d.sample and chemistry_key_for(d.chemistry) == key:
            return d
    return get_dataset("demo-synthetic")
